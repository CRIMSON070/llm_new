def extract_first_valid_json(text: str) -> Optional[Dict[str, Any]]:
    start = text.find('{')
    if start == -1:
        return None
    depth = 0
    in_string = False
    escape = False
    for i in range(start, len(text)):
        char = text[i]
        if char == '"' and not escape:
            in_string = not in_string
        elif char == '\\' and in_string:
            escape = not escape
            continue
        elif not in_string:
            if char == '{':
                depth += 1
            elif char == '}':
                depth -= 1
                if depth == 0:
                    candidate = text[start:i+1]
                    try:
                        return json.loads(candidate)
                    except Exception:
                        pass
        escape = False
    return None


def generate_llm_answer(query: str, context_text: str, model_name: str = "qwen2.5:7b") -> Tuple[str, Optional[Dict[str, Any]]]:
    """
    Generates downstream financial answer using Qwen2.5-7B via the local Ollama API.
    """
    prompt = f"Answer the user's financial question based ONLY on the provided context.\nSelect one predefined operation: 'none', 'extract_single_value', 'absolute_difference', 'percentage_change'.\n\nContext:\n{context_text}\n\nQuestion: {query}\n\nJSON Response:\n"
    
    try:
        resp = requests.post(
            "http://localhost:11434/v1/chat/completions",
            json={
                "model": model_name,
                "messages": [
                    {"role": "user", "content": prompt}
                ],
                "temperature": 0.0,
                "max_tokens": 256
            },
            timeout=60
        )
        if resp.status_code == 200:
            gen_text = resp.json()["choices"][0]["message"]["content"].strip()
            parsed = extract_first_valid_json(gen_text)
            return gen_text, parsed
    except Exception as e:
        print(f"[Generator] Error calling local model: {e}")
        
    return "", None


