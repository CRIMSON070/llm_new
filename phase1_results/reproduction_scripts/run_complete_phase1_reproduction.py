        candidate_pairs = [[q, c["text"][:512]] for c in candidates]
        scores = reranker.compute_score(candidate_pairs)
        if isinstance(scores, float):
            scores = [scores]
            
        scored_candidates = []
        for cid, sc in zip(candidate_cids, scores):
            scored_candidates.append({"chunk_id": cid, "score": float(sc)})
        scored_candidates.sort(key=lambda x: x["score"], reverse=True)
        top_ranked_cids = [c["chunk_id"] for c in scored_candidates]

