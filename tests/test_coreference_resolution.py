"""
tests/test_coreference_resolution.py
=====================================
Unit tests for FinSage Coreference Resolution (Section 3.1 & Appendix A.6).
Validates:
1. Brand, Drug, and Subsidiary entity resolution.
2. Query pronoun anaphora resolution.
3. Chunk-level entity antecedent resolution.
4. End-to-end FinancialQueryExpander integration.
"""

import sys
import os
import unittest

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from src.retrieval.coreference_resolver import CoreferenceResolver
from src.retrieval.financial_expander import FinancialQueryExpander


class TestCoreferenceResolution(unittest.TestCase):

    def setUp(self):
        self.resolver = CoreferenceResolver()
        self.expander = FinancialQueryExpander()

    def test_drug_and_brand_entity_resolution(self):
        cases = [
            ("What was total revenue generated by Mounjaro in 2023?", "ELILILLY", "LLY"),
            ("What was tirzepatide sales performance for the year?", "ELILILLY", "LLY"),
            ("What was Keytruda's worldwide sales for 2024?", "MERCK", "MRK"),
            ("Did Skyrizi and Rinvoq revenues exceed Humira in 2024?", "ABBVIE", "ABBV"),
            ("What was Reality Labs operating loss for 2023?", "META", "META"),
            ("What was total revenue generated by the Optum business platform?", "UNITEDHEALTH", "UNH"),
            ("What was AWS revenue growth in 2023?", "AMAZON", "AMZN"),
            ("How did YouTube advertising perform in 2024?", "ALPHABET", "GOOGL"),
            ("What was Azure cloud revenue growth?", "MICROSOFT", "MSFT"),
        ]
        for query, expected_canon, expected_ticker in cases:
            res = self.resolver.resolve_query(query)
            self.assertTrue(res.is_coreference_resolved, f"Failed to resolve coreference for: {query}")
            self.assertEqual(res.canonical_company, expected_canon)
            self.assertEqual(res.ticker, expected_ticker)

    def test_conversational_anaphora_resolution(self):
        query = "What were its total capital expenditures in 2023?"
        # Without prior context
        res_no_context = self.resolver.resolve_query(query)
        self.assertFalse(res_no_context.is_coreference_resolved)

        # With prior context: Microsoft
        res_with_context = self.resolver.resolve_query(query, prior_context_company="MICROSOFT")
        self.assertTrue(res_with_context.is_coreference_resolved)
        self.assertEqual(res_with_context.canonical_company, "MICROSOFT")
        self.assertEqual(res_with_context.ticker, "MSFT")
        self.assertIn("Microsoft Corporation", res_with_context.enriched_query)

    def test_chunk_antecedent_resolution(self):
        chunk_text = "During fiscal year 2023, the Company recorded revenue from sales of products. Our operating expenses increased."
        doc_name = "LLY_2023_10K"
        resolved_chunk = self.resolver.resolve_chunk_antecedents(chunk_text, doc_name)
        self.assertTrue(resolved_chunk.startswith("[Entity: Eli Lilly and Company | Ticker: LLY | Filing: LLY_2023_10K]"))
        self.assertIn(chunk_text, resolved_chunk)

    def test_financial_expander_end_to_end_integration(self):
        queries = [
            ("What was total revenue generated by Mounjaro (tirzepatide) in fiscal year 2023?", "ELILILLY", "LLY"),
            ("What was Keytruda's worldwide sales for the year ended December 31, 2024?", "MERCK", "MRK"),
            ("Did combined Skyrizi and Rinvoq revenues exceed Humira global revenues in fiscal year 2024?", "ABBVIE", "ABBV"),
            ("What was Reality Labs operating loss for the year ended December 31, 2023?", "META", "META"),
            ("What was total revenue generated by the Optum business platform in fiscal year 2023?", "UNITEDHEALTH", "UNH"),
        ]
        for q, expected_company, expected_ticker in queries:
            exp_res = self.expander.expand(q)
            self.assertEqual(exp_res.detected_company, expected_company, f"Failed for {q}")
            self.assertEqual(exp_res.detected_ticker, expected_ticker, f"Failed for {q}")
            self.assertTrue(exp_res.is_coreference_resolved, f"Failed for {q}")
            self.assertIn(expected_ticker, exp_res.bm25_query)
            self.assertIn(expected_ticker, exp_res.dense_query)


if __name__ == "__main__":
    unittest.main()
